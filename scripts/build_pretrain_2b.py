"""Curate, sample, and token-exactly select the 2B pretraining corpus.

Public code is parsed as inert text. This script never imports or executes it.
"""
from __future__ import annotations

import argparse
import ast
import gzip
import hashlib
import json
import re
import sqlite3
import unicodedata
import warnings
from collections import Counter
from pathlib import Path
from typing import Iterable, Iterator


PERMISSIVE_LICENSES = {
    "mit", "apache-2.0", "apache-2", "bsd-2-clause", "bsd-3-clause",
    "isc", "mpl-2.0", "unlicense", "cc0-1.0", "0bsd",
}
LEAKAGE_MARKERS = (
    "human_eval", "humaneval", "mostly_basic_python_problems", "mbpp",
    "livecodebench", "apps_test", "ds1000", "ds-1000", "codecontests",
)
ZH_SPAM = (
    "点击这里", "扫码关注", "加微信", "联系电话", "在线客服", "免费下载",
    "博彩", "彩票网站", "彩票代理", "成人网站", "最新地址", "上一篇：", "下一篇：",
)
TECH_TERM_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_])(python|sql|database|dataframe|pandas|numpy|algorithm|"
    r"programming|software|source code|debug(?:ging)?|unit tests?|compiler|linux|api|json|"
    r"distributed systems?|machine learning|data science|javascript|github|command line|"
    r"cloud computing|docker|kubernetes|data engineering|etl|parquet|csv|web server|"
    r"network protocol)(?![A-Za-z0-9_])",
    re.IGNORECASE,
)
DATA_CODE_TERMS = (
    "pandas", "numpy", "polars", "sqlalchemy", "sqlite", "postgres", "mysql",
    "dataframe", "csv", "json", "parquet", "etl", "matplotlib", "scipy",
)
AUTOGENERATED_CODE_PATTERN = re.compile(
    r"automatically generated,?\s+do not edit|"
    r"this file (?:is|was) auto(?:matically)?[ -]?generated|"
    r"auto[ -]generated file|generated automatically.{0,80}do not edit",
    re.IGNORECASE,
)
RESERVED_LITERALS = ("<pad>", "<bos>", "<eos>", "<draft>", "<user>", "<assistant>", "<think>", "</think>")


def stable_hash(text: str) -> str:
    return hashlib.blake2b(text.encode("utf-8"), digest_size=16).hexdigest()


def normalized_hash(text: str) -> bytes:
    normalized = " ".join(unicodedata.normalize("NFKC", text).split())
    return hashlib.blake2b(normalized.encode("utf-8"), digest_size=16).digest()


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFC", text).replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n")
    text = "\n".join(line.rstrip() for line in text.splitlines())
    return re.sub(r"\n{4,}", "\n\n\n", text).strip()


def source_paths(root: Path, source: str, files: list[str]) -> list[Path]:
    mapping = {"python": "codeparrot", "zh": "ultrafineweb_zh", "technical": "fineweb_edu"}
    return [root / "raw" / mapping[source] / name for name in files]


def rows_json_gz(path: Path) -> Iterator[dict]:
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def rows_parquet(path: Path, columns: list[str]) -> Iterator[dict]:
    import pyarrow.parquet as pq
    parquet = pq.ParquetFile(path)
    available = set(parquet.schema.names)
    selected = [name for name in columns if name in available]
    for batch in parquet.iter_batches(batch_size=1024, columns=selected):
        yield from batch.to_pylist()


def is_python_candidate(row: dict) -> tuple[bool, str, dict]:
    text = normalize(str(row.get("content", "")))
    path = str(row.get("path", "")).lower()
    license_name = str(row.get("license", "")).strip().lower().replace(" ", "-")
    autogenerated = row.get("autogenerated", False)
    if autogenerated is True or str(autogenerated).strip().lower() in {"true", "1", "yes"}:
        return False, text, {"reason": "autogenerated"}
    if AUTOGENERATED_CODE_PATTERN.search(text[:20_000]):
        return False, text, {"reason": "autogenerated"}
    if license_name not in PERMISSIVE_LICENSES:
        return False, text, {"reason": "license"}
    if not 200 <= len(text) <= 200_000 or any(marker in path for marker in LEAKAGE_MARKERS):
        return False, text, {"reason": "length_or_leakage"}
    if text.count("\n") < 3 or float(row.get("alpha_frac", 1.0) or 0.0) < 0.25:
        return False, text, {"reason": "shape"}
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            ast.parse(text)
    except (SyntaxError, ValueError, MemoryError):
        return False, text, {"reason": "syntax"}
    lower = (path + "\n" + text[:20_000]).lower()
    return True, text, {
        "license": license_name,
        "repo": str(row.get("repo_name", "")),
        "path": str(row.get("path", "")),
        "data_related": any(term in lower for term in DATA_CODE_TERMS),
    }


def is_zh_candidate(row: dict) -> tuple[bool, str, dict]:
    text = normalize(str(row.get("content", row.get("text", ""))))
    if not 300 <= len(text) <= 200_000:
        return False, text, {"reason": "length"}
    cjk = len(re.findall(r"[\u3400-\u9fff]", text))
    visible = len(re.findall(r"\S", text))
    if not visible or cjk / visible < 0.30:
        return False, text, {"reason": "language"}
    if sum(text.count(term) for term in ZH_SPAM) >= 2:
        return False, text, {"reason": "spam"}
    if max((len(line) for line in text.splitlines()), default=0) > 10_000:
        return False, text, {"reason": "long_line"}
    return True, text, {"score": row.get("score"), "url": row.get("url", row.get("source", ""))}


def is_technical_candidate(row: dict) -> tuple[bool, str, dict]:
    text = normalize(str(row.get("text", row.get("content", ""))))
    lower = text.lower()
    if not 500 <= len(text) <= 200_000:
        return False, text, {"reason": "length"}
    hits = {match.group(1).lower() for match in TECH_TERM_PATTERN.finditer(text)}
    if len(hits) < 2 or int(row.get("int_score") or 0) < 3 or lower.count("http") > max(10, len(text) // 1000):
        return False, text, {"reason": "topic_or_links"}
    return True, text, {"score": row.get("score"), "int_score": row.get("int_score"), "technical_terms": sorted(hits), "url": row.get("url", "")}


def iter_source(source: str, paths: Iterable[Path]) -> Iterator[dict]:
    for path in paths:
        if not path.exists():
            raise FileNotFoundError(f"missing raw shard: {path}")
        if source == "python":
            rows = rows_json_gz(path)
        elif source == "zh":
            rows = rows_parquet(path, ["content", "text", "score", "url", "source"])
        else:
            rows = rows_parquet(path, ["text", "content", "score", "int_score", "url", "id"])
        for index, row in enumerate(rows):
            yield {"row": row, "shard": path.name, "index": index}


def curate(config: dict, root: Path, reset: bool) -> dict:
    out_dir = root / "curated"
    out_dir.mkdir(parents=True, exist_ok=True)
    db_path = root / "dedup.sqlite3"
    if reset:
        for path in [db_path, *(out_dir.glob("*.jsonl")), root / "tokenizer_sample.txt", root / "curation_report.json"]:
            path.unlink(missing_ok=True)
    if db_path.exists() or any(out_dir.glob("*.jsonl")):
        raise RuntimeError("curation outputs exist; pass --reset to rebuild")
    conn = sqlite3.connect(db_path)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("CREATE TABLE hashes (hash TEXT PRIMARY KEY)")
    report: dict[str, dict] = {}
    sample_caps = {"python": 14_000_000, "zh": 12_000_000, "technical": 4_000_000}
    with (root / "tokenizer_sample.txt").open("w", encoding="utf-8") as sample:
        for source, spec in config["sources"].items():
            counts = Counter()
            chars = sample_chars = 0
            predicate = {"python": is_python_candidate, "zh": is_zh_candidate, "technical": is_technical_candidate}[source]
            paths = source_paths(root, source, spec["files"])
            with (out_dir / f"{source}.jsonl").open("w", encoding="utf-8") as sink:
                for item in iter_source(source, paths):
                    counts["seen"] += 1
                    accepted, text, meta = predicate(item["row"])
                    if not accepted:
                        counts[f"rejected_{meta['reason']}"] += 1
                        continue
                    digest = stable_hash(text)
                    try:
                        conn.execute("INSERT INTO hashes VALUES (?)", (digest,))
                    except sqlite3.IntegrityError:
                        counts["rejected_exact_duplicate"] += 1
                        continue
                    source_id = f"{source}:{item['shard']}:{item['index']}"
                    split = "validation" if int(stable_hash(source_id)[:8], 16) / 2**32 < config["validation_fraction"] else "train"
                    record = {
                        "text": text,
                        "source": source,
                        "source_id": source_id,
                        "group_id": source_id,
                        "split": split,
                        "revision": spec["revision"],
                        "license": spec["license"],
                        **meta,
                    }
                    sink.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n")
                    counts[f"accepted_{split}"] += 1
                    chars += len(text)
                    if split == "train" and sample_chars < sample_caps[source] and int(digest[:8], 16) % 7 == 0:
                        take = text[: sample_caps[source] - sample_chars]
                        sample.write(take + "\n")
                        sample_chars += len(take)
            conn.commit()
            report[source] = {**counts, "accepted_chars": chars, "tokenizer_sample_chars": sample_chars}
    conn.close()
    (root / "curation_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    return report


def select(config: dict, root: Path, tokenizer_path: Path, reset: bool) -> dict:
    from tokenizers import Tokenizer
    tokenizer = Tokenizer.from_file(str(tokenizer_path))
    if tokenizer.get_vocab_size() != config["tokenizer_vocab_size"]:
        raise ValueError("tokenizer vocabulary does not match corpus config")
    eos = tokenizer.token_to_id("<eos>")
    if eos is None:
        raise ValueError("tokenizer has no <eos>")
    selected_dir = root / "selected"
    selected_dir.mkdir(parents=True, exist_ok=True)
    outputs = [selected_dir / "train.jsonl", selected_dir / "validation.jsonl", selected_dir / "report.json"]
    if reset:
        for path in outputs:
            path.unlink(missing_ok=True)
    if any(path.exists() for path in outputs):
        raise RuntimeError("selection outputs exist; pass --reset to rebuild")
    report: dict[str, dict] = {}
    selected_hashes: set[bytes] = set()
    with outputs[0].open("w", encoding="utf-8") as train_out, outputs[1].open("w", encoding="utf-8") as val_out:
        for source, spec in config["sources"].items():
            target = int(spec["target_tokens"])
            train_tokens = val_tokens = train_docs = val_docs = 0
            skipped_reserved = 0
            skipped_normalized_duplicate = 0
            validation_target = max(1_000_000, target // 200)
            path = root / "curated" / f"{source}.jsonl"
            with path.open(encoding="utf-8") as handle:
                iterator = iter(handle)
                while train_tokens < target or val_tokens < validation_target:
                    batch = []
                    while len(batch) < 256:
                        try:
                            row = json.loads(next(iterator))
                        except StopIteration:
                            break
                        if any(literal in row["text"] for literal in RESERVED_LITERALS):
                            skipped_reserved += 1
                            continue
                        if row["split"] == "validation" and val_tokens >= validation_target:
                            continue
                        if row["split"] == "train" and train_tokens >= target:
                            continue
                        digest = normalized_hash(row["text"])
                        if digest in selected_hashes:
                            skipped_normalized_duplicate += 1
                            continue
                        selected_hashes.add(digest)
                        row.setdefault("revision", spec["revision"])
                        row.setdefault("license", spec["license"])
                        row.setdefault("group_id", row["source_id"])
                        batch.append(row)
                    if not batch:
                        break
                    encodings = tokenizer.encode_batch([row["text"] for row in batch], add_special_tokens=False)
                    for row, encoding in zip(batch, encodings):
                        ids = encoding.ids
                        token_count = len(ids) + 1
                        if row["split"] == "validation":
                            if val_tokens < validation_target:
                                val_out.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
                                val_tokens += token_count
                                val_docs += 1
                            continue
                        if train_tokens >= target:
                            continue
                        remaining = target - train_tokens
                        if token_count > remaining:
                            if remaining < 2:
                                raise RuntimeError("cannot create a useful final record")
                            # Store the one quota-boundary record as IDs. Decoding a byte-level
                            # prefix can cut a multi-byte character and alter its re-encoding.
                            # Pretokenized output keeps the quota exact without that round trip.
                            tail_ids = ids[: remaining - 1] + [eos]
                            row = {
                                "input_ids": tail_ids,
                                "labels": tail_ids,
                                "source": source,
                                "source_id": row["source_id"],
                                "split": "train",
                                "revision": spec["revision"],
                                "license": spec["license"],
                                "group_id": row["group_id"],
                                "truncated_for_exact_quota": True,
                            }
                            token_count = remaining
                        train_out.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
                        train_tokens += token_count
                        train_docs += 1
            if train_tokens != target:
                raise RuntimeError(f"{source}: only {train_tokens:,} clean tokens available; need {target:,}; add shards")
            report[source] = {
                "train_tokens": train_tokens,
                "train_documents": train_docs,
                "validation_tokens": val_tokens,
                "validation_documents": val_docs,
                "skipped_reserved_literal_documents": skipped_reserved,
                "skipped_normalized_duplicate_documents": skipped_normalized_duplicate,
            }
    report["total_train_tokens"] = sum(value["train_tokens"] for value in report.values())
    report["tokenizer_sha256"] = hashlib.sha256(tokenizer_path.read_bytes()).hexdigest()
    outputs[2].write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["curate", "select"])
    parser.add_argument("--config", default="configs/pretrain_2b.json")
    parser.add_argument("--root", default="data/pretrain_2b")
    parser.add_argument("--tokenizer", default="data/pretrain_2b/tokenizer/tokenizer.json")
    parser.add_argument("--reset", action="store_true")
    args = parser.parse_args()
    config = json.loads(Path(args.config).read_text())
    if sum(int(x["target_tokens"]) for x in config["sources"].values()) != int(config["target_tokens"]):
        raise ValueError("source quotas do not sum to target_tokens")
    result = curate(config, Path(args.root), args.reset) if args.command == "curate" else select(config, Path(args.root), Path(args.tokenizer), args.reset)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
