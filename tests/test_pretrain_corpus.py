import json

from tokenizers import Tokenizer, models, pre_tokenizers

from scripts.build_pretrain_2b import is_python_candidate, is_technical_candidate, is_zh_candidate, select


def test_python_filter_enforces_license_syntax_and_benchmark_exclusion():
    base = {
        "content": "def load_rows(path):\n    with open(path) as f:\n        return [line.strip() for line in f]\n" * 3,
        "path": "src/data/reader.py",
        "license": "mit",
        "alpha_frac": 0.7,
    }
    assert is_python_candidate(base)[0]
    assert not is_python_candidate({**base, "license": "gpl-3.0"})[0]
    assert not is_python_candidate({**base, "path": "benchmarks/humaneval/reader.py"})[0]
    assert not is_python_candidate({**base, "content": "def broken("})[0]
    accepted, _, metadata = is_python_candidate({**base, "autogenerated": True})
    assert not accepted
    assert metadata["reason"] == "autogenerated"
    generated = "# Automatically generated, do not edit.\n" + base["content"]
    accepted, _, metadata = is_python_candidate({**base, "content": generated})
    assert not accepted
    assert metadata["reason"] == "autogenerated"


def test_chinese_filter_rejects_navigation_spam():
    useful = "数据处理需要先检查字段类型和缺失值。" * 30
    assert is_zh_candidate({"content": useful})[0]
    spam = useful + "\n点击这里\n扫码关注\n联系电话"
    assert not is_zh_candidate({"content": spam})[0]


def test_technical_filter_uses_word_boundaries_and_multiple_terms():
    noise = ("A capital city has many cultural traditions and historical stories. " * 20)
    assert not is_technical_candidate({"text": noise, "int_score": 4})[0]
    technical = ("Python software can query a SQL database and return a pandas DataFrame. " * 20)
    accepted, _, metadata = is_technical_candidate({"text": technical, "int_score": 3})
    assert accepted
    assert {"python", "software", "sql", "database"}.issubset(metadata["technical_terms"])
    assert not is_technical_candidate({"text": technical, "int_score": 2})[0]


def test_selection_uses_pretokenized_tail_for_exact_quota(tmp_path):
    tokenizer = Tokenizer(models.WordLevel({"<unk>": 0, "<eos>": 1, "a": 2, "b": 3, "c": 4, "d": 5, "e": 6}, unk_token="<unk>"))
    tokenizer.pre_tokenizer = pre_tokenizers.Whitespace()
    tokenizer_path = tmp_path / "tokenizer.json"
    tokenizer.save(str(tokenizer_path))
    curated = tmp_path / "curated"
    curated.mkdir()
    (curated / "python.jsonl").write_text(json.dumps({"text": "a b c d e", "source": "python", "source_id": "one", "split": "train"}) + "\n")
    config = {"tokenizer_vocab_size": 7, "sources": {"python": {
        "target_tokens": 5, "revision": "test-revision", "license": "test-license",
    }}}
    report = select(config, tmp_path, tokenizer_path, reset=False)
    row = json.loads((tmp_path / "selected" / "train.jsonl").read_text())
    assert report["total_train_tokens"] == 5
    assert len(row["input_ids"]) == len(row["labels"]) == 5
    assert row["input_ids"][-1] == tokenizer.token_to_id("<eos>")
    assert row["revision"] == "test-revision"
    assert row["group_id"] == "one"


def test_selection_skips_nfkc_whitespace_duplicates(tmp_path):
    tokenizer = Tokenizer(models.WordLevel({"<unk>": 0, "<eos>": 1, "A": 2, "B": 3, "C": 4}, unk_token="<unk>"))
    tokenizer.pre_tokenizer = pre_tokenizers.Whitespace()
    tokenizer_path = tmp_path / "tokenizer.json"
    tokenizer.save(str(tokenizer_path))
    curated = tmp_path / "curated"
    curated.mkdir()
    rows = [
        {"text": "Ａ  B", "source": "python", "source_id": "one", "split": "train"},
        {"text": "A B", "source": "python", "source_id": "two", "split": "train"},
        {"text": "C", "source": "python", "source_id": "three", "split": "train"},
    ]
    (curated / "python.jsonl").write_text("".join(json.dumps(row) + "\n" for row in rows))
    config = {"tokenizer_vocab_size": 5, "sources": {"python": {
        "target_tokens": 5, "revision": "test", "license": "test",
    }}}
    report = select(config, tmp_path, tokenizer_path, reset=False)
    assert report["python"]["skipped_normalized_duplicate_documents"] == 1
    assert report["total_train_tokens"] == 5
